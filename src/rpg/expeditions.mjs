const neighbors = (x, y) => [
  [x + 1, y],
  [x - 1, y],
  [x, y + 1],
  [x, y - 1],
];
const hash = (x, y) => `${x},${y}`;
export const routeId = (ch, floor) => `${ch}.${floor}`;
export function routeDefinition(ch, floor) {
  if (
    !Number.isInteger(ch) ||
    ch < 0 ||
    ch > 7 ||
    !Number.isInteger(floor) ||
    floor < 0 ||
    floor > 2
  )
    throw Error("未知的探索区域");
  let rows = plans[ch].map((r) => r.split(""));
  if (floor === 1) rows = rows.map((r) => r.reverse());
  if (floor === 2) rows = rows.reverse();
  const tiles = {};
  let start;
  const walk = [];
  rows.forEach((row, y) =>
    row.forEach((c, x) => {
      if (c === "S") {
        start = { x, y };
        row[x] = ".";
      }
      if (c !== "#") walk.push({ x, y });
    }),
  );
  // Place features by graph distance, independently of display orientation.
  const distance = new Map([[hash(start.x, start.y), 0]]),
    q = [start];
  for (let i = 0; i < q.length; i++)
    for (const [x, y] of neighbors(q[i].x, q[i].y))
      if (
        rows[y]?.[x] !== undefined &&
        rows[y][x] !== "#" &&
        !distance.has(hash(x, y))
      ) {
        distance.set(hash(x, y), distance.get(hash(q[i].x, q[i].y)) + 1);
        q.push({ x, y });
      }
  const reachable = walk
    .filter(
      (p) => distance.has(hash(p.x, p.y)) && distance.get(hash(p.x, p.y)) > 1,
    )
    .sort(
      (a, b) =>
        distance.get(hash(a.x, a.y)) - distance.get(hash(b.x, b.y)) ||
        a.y - b.y ||
        a.x - b.x,
    );
  const features = [
    "note0",
    "rune0",
    "battle0",
    "chest",
    "rune1",
    "note1",
    "battle1",
    "rune2",
    "key",
    "note2",
    "exit",
  ];
  const used = new Set();
  features.forEach((f, i) => {
    let index = Math.floor(
      ((i + 1) * reachable.length) / (features.length + 1),
    );
    while (used.has(index)) index = (index + 1) % reachable.length;
    used.add(index);
    const p = reachable[index];
    tiles[hash(p.x, p.y)] = f;
  });
  const story = routeStories[ch][floor];
  return {
    id: routeId(ch, floor),
    chapter: ch,
    floor,
    title: story[0],
    subtitle: story[1],
    notes: story.slice(2),
    rows: rows.map((r) => r.join("")),
    tiles,
    start,
    target: [
      [1, 1, 0],
      [1, 0, 1],
      [0, 1, 1],
    ][(ch + floor) % 3],
    reachable: distance.size,
  };
}
export function newExpedition(ch, floor) {
  const d = routeDefinition(ch, floor);
  return {
    id: d.id,
    chapter: ch,
    floor,
    x: d.start.x,
    y: d.start.y,
    seen: [hash(d.start.x, d.start.y)],
    collected: [],
    runes: [0, 0, 0],
    message:
      "墙上的灯谱：相邻两盏会一起转动。调整三盏符灯，使它们与出口灯谱一致，再带钥匙离开。",
  };
}
export function reveal(ex) {
  const seen = new Set(ex.seen);
  for (let dx = -2; dx <= 2; dx++)
    for (let dy = -2; dy <= 2; dy++)
      if (
        Math.abs(dx) + Math.abs(dy) <= 3 &&
        ex.x + dx >= 0 &&
        ex.x + dx < 13 &&
        ex.y + dy >= 0 &&
        ex.y + dy < 11
      )
        seen.add(hash(ex.x + dx, ex.y + dy));
  return [...seen];
}
export function enterExpedition(state, ch = state.chapter) {
  if (ch > state.unlocked) return state;
  const floor = [0, 1, 2].find((i) => !state.routes.includes(routeId(ch, i)));
  if (floor === undefined) return state;
  if (state.expedition?.chapter === ch && state.expedition.floor === floor)
    return state;
  const s = structuredClone(state);
  s.expedition = newExpedition(ch, floor);
  s.expedition.seen = reveal(s.expedition);
  return s;
}
export function moveExpedition(state, dx, dy) {
  if (!state.expedition || Math.abs(dx) + Math.abs(dy) !== 1)
    return { state, event: null };
  const s = structuredClone(state),
    ex = s.expedition,
    d = routeDefinition(ex.chapter, ex.floor),
    x = ex.x + dx,
    y = ex.y + dy;
  if (!d.rows[y] || d.rows[y][x] === undefined || d.rows[y][x] === "#")
    return { state, event: null };
  ex.x = x;
  ex.y = y;
  ex.seen = reveal(ex);
  const feature = d.tiles[hash(x, y)];
  if (!feature || ex.collected.includes(feature)) {
    ex.message = "石壁上有旧日灯痕。继续探索，寻找符灯与钥匙。";
    return { state: s, event: null };
  }
  if (feature.startsWith("rune")) {
    const i = Number(feature.at(-1));
    ex.runes[i] = 1 - ex.runes[i];
    ex.runes[(i + 1) % 3] = 1 - ex.runes[(i + 1) % 3];
    ex.message = `触动${["青", "朱", "金"][i]}符灯，${["青与朱", "朱与金", "金与青"][i]}两盏灯一同改变。出口需要：${d.target.map((v) => (v ? "亮" : "暗")).join(" · ")}。`;
  }
  if (feature.startsWith("note")) {
    ex.collected.push(feature);
    ex.message = d.notes[Number(feature.at(-1))];
  }
  if (feature === "key") {
    ex.collected.push(feature);
    ex.message = "拾得这条回廊的铜钥。符灯调好以后，就能开启出口。";
  }
  if (feature === "chest") {
    ex.collected.push(feature);
    s.coins += 20 + ex.chapter * 5;
    s.herbs++;
    s.oil++;
    ex.message =
      "打开旅人留下的补给匣：回春散 +1、灯油 +1、铜钱增加。每只匣子只能领取一次。";
  }
  if (feature.startsWith("battle")) {
    ex.message = "前路被雾中的守卫拦住。举灯迎战，或先退一步回营地准备。";
    return {
      state: s,
      event: { type: "battle", feature, chapter: ex.chapter, floor: ex.floor },
    };
  }
  if (feature === "exit") {
    if (!ex.collected.includes("key")) {
      ex.message = "出口铜锁还在。先找到本层的铜钥。";
      return { state: s, event: null };
    }
    if (!ex.runes.every((v, i) => v === d.target[i])) {
      ex.message = `出口灯谱与符灯尚未相合。需要：${d.target.map((v) => (v ? "亮" : "暗")).join(" · ")}。`;
      return { state: s, event: null };
    }
    s.routes.push(d.id);
    s.xp += 45 + ex.chapter * 10;
    s.coins += 25;
    ex.message = "出口已开启。这段路被记进了旅记。";
    return {
      state: s,
      event: { type: "complete", chapter: ex.chapter, floor: ex.floor },
    };
  }
  return { state: s, event: null };
}
export function validateExpedition(input, routes, unlocked) {
  if (input === null || input === undefined) return null;
  const { chapter: ch, floor } = input;
  const d = routeDefinition(ch, floor);
  if (ch > unlocked || routes.includes(d.id)) return null;
  if (
    input.id !== d.id ||
    !Number.isInteger(input.x) ||
    !Number.isInteger(input.y) ||
    d.rows[input.y]?.[input.x] !== "."
  )
    throw Error("回廊位置无效");
  if (
    !Array.isArray(input.collected) ||
    new Set(input.collected).size !== input.collected.length ||
    input.collected.some(
      (k) =>
        !Object.values(d.tiles).includes(k) ||
        k.startsWith("rune") ||
        k === "exit",
    )
  )
    throw Error("回廊记录无效");
  if (
    !Array.isArray(input.runes) ||
    input.runes.length !== 3 ||
    input.runes.some((v) => v !== 0 && v !== 1) ||
    input.runes.reduce((a, b) => a + b, 0) % 2 !== 0
  )
    throw Error("符灯记录无效");
  if (
    !Array.isArray(input.seen) ||
    input.seen.length > 143 ||
    input.seen.some(
      (k) =>
        typeof k !== "string" ||
        !/^\d{1,2},\d{1,2}$/.test(k) ||
        Number(k.split(",")[0]) > 12 ||
        Number(k.split(",")[1]) > 10,
    )
  )
    throw Error("舆图记录无效");
  return {
    id: d.id,
    chapter: ch,
    floor,
    x: input.x,
    y: input.y,
    collected: [...input.collected],
    runes: [...input.runes],
    seen: [...new Set(input.seen)],
    message: "回到上次停下的地方。符灯与铜钥的记录仍在。",
  };
}
